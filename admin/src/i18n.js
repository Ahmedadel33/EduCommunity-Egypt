const LanguageContext = createContext(null);

export function AdminLanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem("language") || "ar");

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    localStorage.setItem("language", language);
    document.title = language === "ar" ? "لوحة الأدمن — EduCommunity" : "Admin panel — EduCommunity";
  }, [language]);

  const t = (text) => language === "en" ? translations[text] || text : text;

  return createElement(LanguageContext.Provider, { value: { language, setLanguage, t } }, children);
}

export function useAdminI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useAdminI18n must be used within AdminLanguageProvider");
  return context;
}
